/**
 * The two benchmark suites, and what distinguishes them.
 *
 * `northbeam` runs against the catalog this repo seeds. Owning the data means it
 * can test categories a hand-built catalog can express, like usage ranking,
 * deprecation traps and failing assertions, which no public demo catalog carries
 * on an OSS server.
 *
 * `showcase` runs against `showcase-ecommerce`, DataHub's own published demo
 * datapack, holding 1,065 entities nobody here designed. It answers the fair
 * objection that a high score on your own catalog is partly built in.
 *
 * Same agent loop, same deterministic scorer, same two arms. Only the catalog
 * and the questions differ.
 */

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { BENCHMARK, CATEGORIES, type Category, type EvalCase } from "./benchmark";
import { SHOWCASE_BENCHMARK, SHOWCASE_CATEGORIES, type ShowcaseCategory } from "./benchmark-showcase";

export type SuiteName = "northbeam" | "showcase" | "holdout";

/**
 * The held-out suite is not written here, and that is the whole point of it.
 * `evals/holdout/cases.json` is generated by a different vendor's model that saw
 * a flat dump of the catalog and nothing else — not our prompts, not our tools,
 * not our scorer, not the cases above. See `evals/holdout/README.md`.
 *
 * It is read off disk rather than imported so that the questions and the code
 * that runs them stay visibly separate: the file can be diffed, hashed and
 * checked against the catalog it was written from without reading TypeScript.
 */
const HOLDOUT_PATH = path.join(process.cwd(), "evals", "holdout", "cases.json");

function loadHoldout(): EvalCase<string>[] {
  if (!existsSync(HOLDOUT_PATH)) return [];
  const file = JSON.parse(readFileSync(HOLDOUT_PATH, "utf8")) as { cases: EvalCase<string>[] };
  return file.cases ?? [];
}

const HOLDOUT_CASES = loadHoldout();

export interface Suite {
  name: SuiteName;
  /** Human-readable catalog description for the scorecard header. */
  catalog: string;
  cases: EvalCase<string>[];
  categories: string[];
  /**
   * The control arm's prompt. Deliberately NOT instaboard's system prompt with
   * the tools removed, which would be a strawman that refuses every question.
   * It is the honest counterfactual: a capable general assistant answering a new
   * hire's question with no access to the company's catalog, which is exactly
   * what a new hire gets from an off-the-shelf chatbot today.
   */
  blindPrompt: string;
  /**
   * The warehouse-introspection arm's prompt. This arm has real tools — table
   * and column listings straight out of `information_schema` — but no catalog.
   * It exists to answer the fair objection that the grounded-vs-blind gap partly
   * measures *having tools* rather than *having DataHub*. It gets the same
   * encouragement to be specific, and is told to look things up rather than
   * guess, so anything it still cannot answer is a thing the schema does not
   * contain.
   */
  schemaPrompt: string;
  /** Basename for results files under evals/results/. */
  resultsPrefix: string;
  /** True when the suite has no demo fixture and must run against live DataHub. */
  requiresLive: boolean;
  /** Shown in the scorecard so readers know how to reproduce it. */
  reproduce: string[];
}

